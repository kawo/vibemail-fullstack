-- VibeMail Engine v1.3: uploaded attachments (CONTRACT.md §5.5, used by §4.14 and §4.3).
--
-- Every statement is idempotent: re-running this file is a no-op and must exit 0.
--
-- One row per reserved upload; the bytes live in the private Storage bucket
-- `attachments` at storage_path ('{user_id}/{id}'). RLS is enabled with NO
-- policies, as on users and messages (§5.1, §5.2): only service_role, which
-- bypasses RLS, reads and writes. Tenant isolation itself is enforced in src/db
-- (§5.3). The bucket gets no Storage policies either: uploads go through signed
-- URLs and reads through the service role.

-- ---------------------------------------------------------------------------
-- public.attachments: one uploaded file (§5.5)
-- ---------------------------------------------------------------------------

create table if not exists public.attachments (
  -- Generated by the server (§4.14 step 3); no default on purpose.
  id           uuid        not null,
  user_id      uuid        not null,
  filename     text        not null,
  mime_type    text        not null,
  size_bytes   integer     not null,
  storage_path text        not null,
  created_at   timestamptz not null default now()
);

do $$
begin
  if not exists (select 1 from pg_constraint where conname = 'attachments_pkey'
                 and conrelid = 'public.attachments'::regclass) then
    alter table public.attachments add constraint attachments_pkey primary key (id);
  end if;

  if not exists (select 1 from pg_constraint where conname = 'attachments_user_id_fkey'
                 and conrelid = 'public.attachments'::regclass) then
    alter table public.attachments add constraint attachments_user_id_fkey
      foreign key (user_id) references auth.users (id) on delete cascade;
  end if;

  if not exists (select 1 from pg_constraint where conname = 'attachments_storage_path_key'
                 and conrelid = 'public.attachments'::regclass) then
    alter table public.attachments add constraint attachments_storage_path_key unique (storage_path);
  end if;

  if not exists (select 1 from pg_constraint where conname = 'attachments_filename_length_check'
                 and conrelid = 'public.attachments'::regclass) then
    alter table public.attachments add constraint attachments_filename_length_check
      check (char_length(filename) between 1 and 255);
  end if;

  -- 25 MB per file (§4.14); the declared size, re-checked by the bucket below.
  if not exists (select 1 from pg_constraint where conname = 'attachments_size_bytes_check'
                 and conrelid = 'public.attachments'::regclass) then
    alter table public.attachments add constraint attachments_size_bytes_check
      check (size_bytes between 1 and 26214400);
  end if;
end;
$$;

create index if not exists attachments_user_id_created_at_idx
  on public.attachments (user_id, created_at desc);

alter table public.attachments enable row level security;

-- ---------------------------------------------------------------------------
-- Storage bucket `attachments` (§5.5): private, 25 MB per object, any type
-- ---------------------------------------------------------------------------

insert into storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
values ('attachments', 'attachments', false, 26214400, null)
on conflict (id) do update
  set public = false,
      file_size_limit = 26214400,
      allowed_mime_types = null;
